export type RouteId = keyof typeof ROUTES;
export const ROUTE_IDS = Object.keys(ROUTES) as RouteId[];

type Out<T> = T extends z.ZodType ? z.output<T> : undefined;

/** What a handler is given for a route: its parameters, query and body, already checked. */
export interface RouteInput<I extends RouteId> {
  params: Out<(typeof ROUTES)[I] extends { params: infer P } ? P : undefined>;
  query: Out<(typeof ROUTES)[I] extends { query: infer Q } ? Q : undefined>;
  body: Out<(typeof ROUTES)[I] extends { body: infer B } ? B : undefined>;
}

/** What a handler gives back for a route. */
export type RouteOutput<I extends RouteId> = (typeof ROUTES)[I]['response'] extends z.ZodType ? z.output<(typeof ROUTES)[I]['response']> : void;
