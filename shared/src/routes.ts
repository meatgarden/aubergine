/**
 * Every route of the public API, declared once.
 *
 * The server registers its handlers from this list, the description of the
 * API (`/v1/openapi.json`) is generated from it, and from that the client
 * and the reference. Nothing about a route's address, method, input, output
 * or the permission it needs is written anywhere else.
 *
 * Adding a route is adding an entry here and a handler of the same name in
 * the daemon; then `pnpm generate` brings the client and the reference up
 * to date.
 */

export type RouteMethod = 'GET' | 'POST' | 'PATCH' | 'PUT' | 'DELETE';

export const ROUTE_TAGS = ['Server', 'Canvases', 'Sessions', 'Notes', 'Layout', 'Workflows', 'Runs', 'Events', 'Tokens', 'For a session itself'] as const;
export type RouteTag = (typeof ROUTE_TAGS)[number];

export interface RouteSpec {
  method: RouteMethod;
  /** The address, with `:name` for each parameter: `/v1/canvases/:canvasId`. */
  path: string;
  tag: RouteTag;
  /** What it does, in a few words. */
  summary: string;
  /** More, when a few words are not enough. */
  description?: string;
  /**
   * What `authorize` is asked before anything else happens. `null` means any
   * caller that is who it says it is: the route needs no permission.
   */
  action: Action | null;
  /**
   * Fields of the body that need a different permission from the route's
   * own: sending one of them asks for that action as well (or instead, when
   * nothing else is sent).
   */
  fieldActions?: Record<string, Action>;
  /** The parameters in the address. One whose name ends in `Id` is an ID. */
  params?: z.ZodObject;
  query?: z.ZodType;
  body?: z.ZodType;
  /** The body may be left out altogether, and is then taken as `{}`. */
  bodyOptional?: boolean;
  /** What comes back; `null` for no content. */
  response: z.ZodType | null;
  status: 200 | 201 | 204;
  /** A create: takes an `Idempotency-Key` header, so that a repeat makes nothing more. */
  idempotent?: boolean;
  /** A list: takes `limit` and `cursor`, and answers with `items` and `nextCursor`. */
  paged?: boolean;
  /** Not one answer but a stream of server-sent events, each of this shape. */
  stream?: z.ZodType;
  /** Besides the errors every route can give: the further ones this one can. */
  errors?: readonly (404 | 409 | 503)[];
}

