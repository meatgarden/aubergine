/**
 * `shared/src/token-names.generated.ts`: the name of every custom property `web/src/tokens.css` declares, in the order
 * it declares them, and whether it is a color (one of the blocks a color theme gives values to). The stylesheet stays
 * the one place the tokens are written; this copy is what the list of hooks (`UI_HOOKS`), `docs/hooks.md` and the starter
 * stylesheet are made from, and `pnpm generate --check` fails when it is out of date.
 */
export function tokenNamesFile(tokensCss: string): string {
  const plain = tokensCss.replace(/\/\*[\s\S]*?\*\//g, '');
  const blocks = [...plain.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => ({ selector: (m[1] ?? '').trim(), body: m[2] ?? '' }));
  const seen = new Map<string, boolean>();
  for (const block of blocks) {
    // A block that a theme gives values to is about color: it is also drawn for an element marked data-theme-preview.
    const color = block.selector.includes('data-theme-preview');
    for (const declared of block.body.matchAll(/(?:^|;)\s*--([a-z0-9-]+)\s*:/g)) {
      const name = declared[1] ?? '';
      if (!seen.has(name)) seen.set(name, color);
    }
  }
  if (seen.size === 0) throw new Error('No custom property was found in tokens.css.');
  return [
    '// Generated by `pnpm generate` from web/src/tokens.css. Do not edit: change the stylesheet.',
    '',
    '/** Every token the page declares, in the order tokens.css declares it, and whether a color theme gives it a value. */',
    'export const TOKEN_NAMES: readonly { name: string; color: boolean }[] = [',
    ...[...seen].map(([name, color]) => `  { name: '${name}', color: ${color} },`),
    '];',
    '',
  ].join('\n');
}
