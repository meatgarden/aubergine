import { openApiDocument, renderGuide } from '@aubergine/shared';
import { emitClient } from './emit-client';
import { emitDocs } from './emit-docs';

/**
 * Everything that is generated from the description of the API, or from the
 * guide for agents, and kept in the repository, by path from the repository's root. The script writes
 * these; a test fails when what is committed differs.
 *
 * The version is left out of what is generated, so that a release does not
 * change these files.
 */
export function generatedFiles(): Record<string, string> {
  const document = openApiDocument({ version: '0' });
  return {
    'client/src/generated.ts': emitClient(document),
    'docs/api.md': emitDocs(document),
    'docs/for-agents.md': guideFile(),
  };
}

/** The whole guide for agents as a file: what `aubergine guide --all` prints, under a line saying where it comes from. */
export function guideFile(): string {
  return `<!-- Generated by \`pnpm generate\` from shared/src/guide.ts. Do not edit: change the guide there. -->\n\n${renderGuide({ all: true })}\n`;
}
