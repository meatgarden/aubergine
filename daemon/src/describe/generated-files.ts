import { readFileSync } from 'node:fs';
import path from 'node:path';
import { elementReferencePage, hooksReferencePage, openApiDocument, projectFileReferencePage, renderGuide, settingsJsonSchema, settingsReferencePage, templateReferencePage, themeFileJsonSchema } from '@aubergine/shared';
import { packageRoot } from '../package-root';
import { emitClient } from './emit-client';
import { emitDocs } from './emit-docs';
import { themeColorsFile } from './theme-colors';
import { tokenNamesFile } from './token-names';

/**
 * Everything that is generated from the description of the API, or from the
 * guide for agents, and kept in the repository, by path from the repository's root. The script writes
 * these; a test fails when what is committed differs.
 *
 * The version is left out of what is generated, so that a release does not
 * change these files.
 */
export function generatedFiles(): Record<string, string> {
  const document = openApiDocument({ version: '0' });
  return {
    'client/src/generated.ts': emitClient(document),
    'docs/api.md': emitDocs(document),
    'docs/for-agents.md': guideFile(),
    'docs/project-file.md': `<!-- Generated by \`pnpm generate\` from the descriptions in shared/src/project-file.ts. Do not edit: change the descriptions there. -->\n\n${projectFileReferencePage()}\n`,
    'docs/settings.md': `<!-- Generated by \`pnpm generate\` from the descriptions in shared/src/settings.ts and shared/src/themes.ts. Do not edit: change the descriptions there. -->\n\n${settingsReferencePage()}\n`,
    'docs/templates.md': `<!-- Generated by \`pnpm generate\` from the placeholders registered in shared/src/templates.ts. Do not edit: change them there. -->\n\n${templateReferencePage()}\n`,
    'docs/config.schema.json': `${JSON.stringify(settingsJsonSchema(), null, 2)}\n`,
    'docs/theme.schema.json': `${JSON.stringify(themeFileJsonSchema(), null, 2)}\n`,
    'shared/src/theme-colors.generated.ts': themeColorsFile(stylesheet('tokens.css'), stylesheet('themes.css')),
    'shared/src/token-names.generated.ts': tokenNamesFile(stylesheet('tokens.css')),
    'docs/hooks.md': `<!-- Generated by \`pnpm generate\` from the list of hooks in shared/src/hooks.ts and the tokens in web/src/tokens.css. Do not edit: change them there. -->\n\n${hooksReferencePage()}\n`,
    'docs/element.md': `<!-- Generated by \`pnpm generate\` from the descriptions in shared/src/workflows.ts and shared/src/drafts.ts. Do not edit: change the descriptions there. -->\n\n${elementReferencePage()}\n`,
  };
}

/** A stylesheet of the web app, from this checkout: the colors of the built-in themes are written there and nowhere else. */
const stylesheet = (name: string): string => readFileSync(path.join(packageRoot(), 'web', 'src', name), 'utf8');

/** The whole guide for agents as a file: what `aubergine guide --all` prints, under a line saying where it comes from. */
export function guideFile(): string {
  return `<!-- Generated by \`pnpm generate\` from shared/src/guide.ts. Do not edit: change the guide there. -->\n\n${renderGuide({ all: true })}\n`;
}
