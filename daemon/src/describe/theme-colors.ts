import { COLOR_THEMES, THEME_COLORS } from '@aubergine/shared';

/**
 * `shared/src/theme-colors.generated.ts`: for each built-in theme, the value of each color a person may set, read from
 * the stylesheets that draw them (`web/src/tokens.css` for Light and Dark, `web/src/themes.css` for the rest). The
 * stylesheets stay the one place the colors are written; this copy is for what runs outside the browser (a new theme
 * file's starting values, Settings' word about contrast), and `pnpm generate --check` fails when it is out of date.
 */
export function themeColorsFile(tokensCss: string, themesCss: string): string {
  const plain = `${tokensCss}\n${themesCss}`.replace(/\/\*[\s\S]*?\*\//g, '');
  const blocks = [...plain.matchAll(/([^{}]+)\{([^{}]*)\}/g)].map((m) => ({ selector: m[1] ?? '', body: m[2] ?? '' }));
  const lines: string[] = [];
  for (const theme of COLOR_THEMES) {
    const block = blocks.find((one) => one.selector.split(',').some((part) => part.trim() === `[data-theme-preview='${theme.id}']`));
    if (!block) throw new Error(`No block of colors for the theme ${theme.id} in the stylesheets.`);
    const values = new Map([...block.body.matchAll(/(--[a-z0-9-]+):\s*([^;]+);/g)].map((d) => [d[1] ?? '', (d[2] ?? '').trim()]));
    const pairs = THEME_COLORS.map((name) => {
      const value = values.get(`--${name}`);
      if (!value || !/^#[0-9a-f]{6}$/.test(value)) throw new Error(`The theme ${theme.id} has no plain color for --${name}.`);
      return `    '${name}': '${value}',`;
    });
    lines.push(`  '${theme.id}': {`, ...pairs, '  },');
  }
  return [
    '// Generated by `pnpm generate` from web/src/tokens.css and web/src/themes.css. Do not edit: change the stylesheets.',
    "import type { ColorThemeId, ThemeColor } from './themes';",
    '',
    '/** For each built-in theme, the value of each color a person may set, as the stylesheets draw it. */',
    'export const BUILT_IN_THEME_COLORS: Record<ColorThemeId, Record<ThemeColor, string>> = {',
    ...lines,
    '};',
    '',
  ].join('\n');
}
