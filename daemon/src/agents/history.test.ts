const at = (minute: number): string => `2026-03-10T10:${String(minute).padStart(2, '0')}:00.000Z`;
const you = (text: string, minute: number, more: object = {}): object => ({ type: 'user', timestamp: at(minute), cwd: project, sessionId: A, message: { role: 'user', content: text }, ...more });
const agent = (text: string, minute: number, tools: object[] = []): object => ({ type: 'assistant', timestamp: at(minute), cwd: project, message: { role: 'assistant', content: [{ type: 'text', text }, ...tools] } });
const result = (text: string, minute: number): object => ({ type: 'user', timestamp: at(minute), cwd: project, message: { role: 'user', content: [{ type: 'tool_result', content: text }] } });

async function conversation(id: string, lines: (object | string)[], folder: string = project): Promise<string> {
  const dir = path.join(home, '.claude', 'projects', projectFolderName(folder) as string);
  await mkdir(dir, { recursive: true });
  const file = path.join(dir, `${id}.jsonl`);
  await writeFile(file, `${lines.map((line) => (typeof line === 'string' ? line : JSON.stringify(line))).join('\n')}\n`);
  return file;
}

